#!/usr/bin/env python3
"""Turn the raw GitHub pages in ``corpus/raw/`` into a readable corpus.

Outputs (in ``corpus/``):

* ``<reviewer>_comments.jsonl``  one record per comment (inline + conversation + review bodies)
* ``<reviewer>_comments.md``     the same, human-readable, grouped by repository and PR
* ``stats.md``                   counts by repository, kind, year and directory

Works with Python 3.9+ and no third-party packages.
"""
from __future__ import annotations

import argparse
import collections
import glob
import json
import re
from pathlib import Path


def load_pages(pattern: str) -> list:
    out: list = []
    for f in sorted(glob.glob(pattern)):
        d = json.loads(Path(f).read_text())
        if isinstance(d, list):
            out += d
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--reviewer", default="keewis")
    ap.add_argument("--raw", default=Path(__file__).parent / "raw", type=Path)
    ap.add_argument("--out", default=Path(__file__).parent, type=Path)
    args = ap.parse_args()

    records: list = []
    slugs = sorted({re.match(r"(.+?)_(comments|issue_comments|pulls)_\d+\.json", Path(f).name).group(1)
                    for f in glob.glob(str(args.raw / "*_*_*.json"))
                    if re.match(r"(.+?)_(comments|issue_comments|pulls)_\d+\.json", Path(f).name)})
    for s in slugs:
        repo_full = None
        for c in load_pages(str(args.raw / f"{s}_comments_*.json")):
            if c["user"]["login"] != args.reviewer:
                continue
            repo_full = repo_full or "/".join(c["html_url"].split("/")[3:5])
            records.append({
                "repo": repo_full, "kind": "inline",
                "pr": int(c["pull_request_url"].rsplit("/", 1)[1]),
                "created_at": c["created_at"], "path": c["path"],
                "line": c.get("original_line") or c.get("line"),
                "commit": c.get("original_commit_id"),
                "diff_hunk": c.get("diff_hunk"), "body": c["body"], "url": c["html_url"],
            })
        for c in load_pages(str(args.raw / f"{s}_issue_comments_*.json")):
            if c["user"]["login"] != args.reviewer:
                continue
            repo_full = repo_full or "/".join(c["html_url"].split("/")[3:5])
            is_pr = "/pull/" in c["html_url"]
            records.append({
                "repo": repo_full, "kind": "pr_conversation" if is_pr else "issue",
                "pr": int(c["issue_url"].rsplit("/", 1)[1]) if is_pr else None,
                "issue": None if is_pr else int(c["issue_url"].rsplit("/", 1)[1]),
                "created_at": c["created_at"], "body": c["body"], "url": c["html_url"],
            })
        for f in glob.glob(str(args.raw / f"{s}_reviews_*.json")):
            for r in json.loads(Path(f).read_text()):
                if r["user"]["login"] != args.reviewer or not (r.get("body") or "").strip():
                    continue
                records.append({
                    "repo": repo_full, "kind": "review_summary", "state": r["state"],
                    "pr": int(r["pull_request_url"].rsplit("/", 1)[1]),
                    "created_at": r["submitted_at"], "body": r["body"], "url": r["html_url"],
                })

    records.sort(key=lambda r: (r["repo"] or "", r.get("pr") or r.get("issue") or 0, r["created_at"]))
    jsonl = args.out / f"{args.reviewer}_comments.jsonl"
    jsonl.write_text("".join(json.dumps(r, ensure_ascii=False) + "\n" for r in records))

    # readable markdown
    md = [f"# Review corpus of `{args.reviewer}`", "",
          f"{len(records)} comments. Generated by `build_corpus.py`; do not edit by hand.", ""]
    for repo, group in itertools_groupby(records, key=lambda r: r["repo"]):
        md.append(f"## {repo}\n")
        for key, g2 in itertools_groupby(group, key=lambda r: (r["kind"] == "issue", r.get("pr") or r.get("issue"))):
            is_issue, num = key
            md.append(f"### {'issue' if is_issue else 'PR'} #{num}\n")
            for r in g2:
                where = f" `{r['path']}` L{r['line']}" if r["kind"] == "inline" else f" ({r['kind']})"
                md.append(f"**{r['created_at'][:10]}**{where}  ")
                if r.get("diff_hunk"):
                    tail = "\n".join(r["diff_hunk"].splitlines()[-3:])
                    md.append("```diff\n" + tail + "\n```")
                md.append(r["body"].strip() + "\n")
    (args.out / f"{args.reviewer}_comments.md").write_text("\n".join(md))

    # stats
    by = collections.Counter((r["repo"], r["kind"]) for r in records)
    by_year = collections.Counter((r["repo"], r["created_at"][:4]) for r in records)
    by_dir = collections.Counter(
        (r["repo"], str(Path(r["path"]).parent).split("/")[0] if r.get("path") else "-")
        for r in records if r["kind"] == "inline")
    lines = ["# Corpus statistics", "", "| repo | kind | n |", "|---|---|---|"]
    lines += [f"| {k[0]} | {k[1]} | {v} |" for k, v in sorted(by.items())]
    lines += ["", "| repo | year | n |", "|---|---|---|"]
    lines += [f"| {k[0]} | {k[1]} | {v} |" for k, v in sorted(by_year.items())]
    lines += ["", "Inline comments by top-level directory:", "", "| repo | dir | n |", "|---|---|---|"]
    lines += [f"| {k[0]} | {k[1]} | {v} |" for k, v in by_dir.most_common()]
    (args.out / "stats.md").write_text("\n".join(lines) + "\n")
    print(f"{len(records)} records -> {jsonl.name}, {args.reviewer}_comments.md, stats.md")


def itertools_groupby(items, key):
    import itertools
    return itertools.groupby(items, key=key)


if __name__ == "__main__":
    main()
